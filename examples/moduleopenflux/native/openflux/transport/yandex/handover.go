package yandex

// Handover — сеть под транспортом сменилась (событие хоста, MODULE_API §2.8). Дословная копия
// openflux-server теперь несёт это сама — ForceReconnect и рвёт живую сессию, и (что старая
// версия этого файла не умела) обрывает ожидание backoff между попытками, если сессии как раз нет:
// без этого "netback" после реального обрыва сети ждал бы весь накопленный backoff (до 30с)
// впустую, хотя сеть уже вернулась. Модулю остаётся только назвать вещь его именем в терминах §2.8.
//
// Отдельным файлом, а не правкой `yandex.go`: тот — дословная копия openflux-server, и апстрим-бамп
// сводится к перезаписи файла.
func (t *YandexDocsTransport) Handover() {
	t.ForceReconnect()
}
