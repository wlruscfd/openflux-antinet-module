//go:build android

package main

// КАНОН shared/dns — резолверы САМОЙ ОС, android-половина. Парные половины —
// `dnsshim_system_unix.go` (linux/darwin) и `dnsshim_system_windows.go`, имя и сигнатура там ТЕ ЖЕ,
// поэтому общий код модуля зовёт `systemDNSServers()` без единого build-тега у себя.
//
// ⛔ ПОЧЕМУ ОТДЕЛЬНО ОТ UNIX, хотя `GOOS=android` активирует и тег `unix`. Там половина читает
// `/etc/resolv.conf`, которого на Android не существует: ОС не публикует свои резолверы в файловой
// системе, а `getprop net.dns1` снят с Android 8. Изнутри процесса взять их неоткуда — именно
// поэтому Go's `dnsReadConfig` и падает на `127.0.0.1:53` (см. `protectedNetResolver`).
//
// ⛔ НО ЭТО НЕ ЗНАЧИТ, ЧТО ИХ НЕТ. Адреса известны ХОСТУ: он читает их у платформы
// (`LinkProperties.dnsServers` ФИЗИЧЕСКОЙ сети — `ModuleManager.physicalDnsServersCsv` на Android,
// `SingboxConfigGenerator.PhysicalDnsServersCsv` на Desktop) и присылает ключом `DNS_SERVERS` при
// старте и событием `dns=` на каждой смене сети. Системный резолвер Android (netd) берёт резолверы
// ИЗ ТОГО ЖЕ источника, поэтому присланный список — не «замена» резолверам ОС, а буквально они.
//
// Разница с unix-половиной, таким образом, только в ПУТИ ДОСТАВКИ: там список читается из файла,
// здесь его приносит хост. Отвечают обе на один вопрос — «какими резолверами пользуется система».

// systemDNSServers — резолверы, которыми пользуется система. Пусто — легитимный ответ: хост не
// смог определить физическую сеть (её нет, либо DNS на ней не назначены). Тогда их нет и у
// системного резолвера тоже, и вызывающий обязан считать это за «резолвить нечем», а не за повод
// пойти в обход через TUN.
func systemDNSServers() []string {
	return hostDNSServers()
}
