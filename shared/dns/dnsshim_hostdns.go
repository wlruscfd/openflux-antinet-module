package main

// КАНОН shared/dns — СПИСОК РЕЗОЛВЕРОВ, ПРИСЛАННЫЙ ХОСТОМ.
//
// ⛔ ЗАЧЕМ ОТДЕЛЬНОЕ ХРАНИЛИЩЕ. На Android резолверы системы процессу недоступны: `/etc/resolv.conf`
// там не существует, а netd под VPN резолвит в туннель. Но САМИ АДРЕСА при этом известны — хост
// читает их у платформы (`LinkProperties.dnsServers` физической сети) и присылает: ключом
// `DNS_SERVERS` при старте и событием `dns=` на каждой смене сети. Другого источника у системного
// резолвера Android НЕТ — netd берёт их оттуда же, — поэтому присланный список И ЕСТЬ «резолверы
// ОС» для всех, кто внутри процесса.
//
// ⛔ ЗАПОЛНЯЕТСЯ КАНОНАМИ, НЕ МОДУЛЕМ. Пишут сюда `parseConfig` (shared/hostproto — разбирает
// конфиг при старте) и `handleHostEvent` (он же — принимает `dns=`), то есть ровно те две точки,
// через которые список физически попадает в процесс. Требовать вызова от модуля значило бы
// раздать обязанность, которую каждый автор выполнит по-своему или забудет, — а плата за «забыл»
// здесь не отказ сборки, а молчаливая потеря фоллбэка на одной из платформ.
//
// Оба писателя живут в main-пакете helper'а вместе с этим файлом: `hostproto` и `dnsshim`
// инжектируются БЕЗУСЛОВНО, поэтому связь между ними есть всегда, а не по флагу.

import "sync"

var (
	hostDNSMu       sync.RWMutex
	hostDNSList     []string
	hostDNSWatchers []func([]string)
)

// onHostDNSServers — подписаться на КАЖДЫЙ новый список от хоста. Подписчик получает уже
// разобранный список и вызывается синхронно, на горутине события.
//
// ⛔ ЗАЧЕМ. Держатель кэширующего резолвера обязан на смену сети не только взять новые серверы, но
// и сбросить кэш: записи в нём получены через ПРЕЖНЮЮ сеть и к новой отношения не имеют. Пока это
// была обязанность модуля, она выглядела как пять строк в обработчике событий — и ровно так же
// молча не выполнялась у того, кто про неё не прочитал: резолв продолжал бить в резолверы ушедшей
// сети, транспорт при этом жив, и снаружи это выглядит как «модуль не заметил смены сети».
//
// Подписка, а не прямой вызов: прокладка инжектируется ВСЕГДА, а кэширующий резолвер — по флагу
// `dnsResolver`, и знать о его типе она не может. Функция — ровно та граница, через которую
// безгейтовая половина разговаривает с гейтованной.
func onHostDNSServers(fn func([]string)) {
	if fn == nil {
		return
	}
	hostDNSMu.Lock()
	hostDNSWatchers = append(hostDNSWatchers, fn)
	hostDNSMu.Unlock()
}

// rememberHostDNSServers — запомнить список, пришедший от хоста. Принимает СЫРУЮ строку в формате
// `DNS_SERVERS`/`dns=` (`ip[,ip...]`), разбирает её канонным `normalizeDNSServers` — тем же, каким
// разбирает свой список кэширующий резолвер.
//
// Пустой разбор НЕ применяется: хост шлёт пустое, когда не смог определить физическую сеть, и
// затирать этим рабочий список означало бы терять последнее, что осталось, ровно в тот момент,
// когда связи и так нет.
func rememberHostDNSServers(csv string) {
	normalized := normalizeDNSCsv(csv)
	if len(normalized) == 0 {
		return
	}
	hostDNSMu.Lock()
	hostDNSList = normalized
	// Снимок подписчиков под тем же локом, вызов — ВНЕ его: подписчик идёт в чужой код (сброс
	// кэша резолвера берёт свой мьютекс), и держать наш замок на это время значило бы связать два
	// независимых замка в один порядок — то есть завести ABBA там, где его не было.
	watchers := append([]func([]string){}, hostDNSWatchers...)
	hostDNSMu.Unlock()

	for _, fn := range watchers {
		fn(normalized)
	}
}

// hostDNSServers — снимок списка. Возвращается КОПИЯ: читатель (`systemDNSServers` на Android)
// отдаёт её наружу, а писатель может заменить слайс в любой момент — событие `dns=` приходит на
// своей горутине, пока резолвы идут на других.
func hostDNSServers() []string {
	hostDNSMu.RLock()
	defer hostDNSMu.RUnlock()
	return append([]string(nil), hostDNSList...)
}
