package main

// Замер шага protect ОДНОГО дозвона. Отдельный файл БЕЗ build-тега намеренно: сам клиент
// (protect_android.go) существует только под Android, а тип нужен и в общем коде helper'а,
// который компилируется под все платформы. Держать тип под `//go:build android` означало бы
// ломать десктопную сборку любого модуля, который его упоминает.
//
// Экземпляр — на каждый дозвон (стековая переменная), НЕ глобал: `Control` зовётся на горутине
// дозвона, и параллельные соединения иначе перезаписывали бы замеры друг друга.
type protectStat struct {
	elapsedMs float64 // сколько занял SCM_RIGHTS-обмен с protect-сервисом AntiNet
	attempts  int     // попыток понадобилось (1 — норма; 5 — сервис не отвечал вовсе)
	firstErr  string  // шаг+errno ПЕРВОГО провала (пусто, если прошло с первой попытки)
}
